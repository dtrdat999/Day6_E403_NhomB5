export const MOCK_PREVIOUS_MONTH_TOTAL = 8500000;

export function calculateTotalExpense(txs: Transaction[]): number {
  return txs
    .filter(t => t.amount < 0 && !t.excludeFromExpense)
    .reduce((sum, t) => sum + Math.abs(t.amount), 0);
}

export function groupByCategory(txs: Transaction[]): Record<string, number> {
  const groups: Record<string, number> = {};
  txs
    .filter(t => t.amount < 0 && !t.excludeFromExpense)
    .forEach(t => {
      const cat = t.category;
      groups[cat] = (groups[cat] || 0) + Math.abs(t.amount);
    });
  return groups;
}

export function formatCurrency(amount: number): string {
  return new Intl.NumberFormat('vi-VN').format(Math.abs(amount)) + 'đ';
}

export function getUnclassifiedTransactions(txs: Transaction[]): Transaction[] {
  return txs.filter(t => t.confidence !== 'high' && !t.excludeFromExpense);
}

export function getRecurringTransactions(txs: Transaction[]): Transaction[] {
  return txs.filter(t => t.isRecurring && t.reminderCandidate);
}
